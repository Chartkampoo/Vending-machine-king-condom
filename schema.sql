SET NAMES utf8mb4;
SET time_zone = '+07:00';

CREATE DATABASE IF NOT EXISTS vending_machine
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE vending_machine;

CREATE TABLE products (
  id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slot_code     CHAR(2)      NOT NULL UNIQUE,
  name_th       VARCHAR(120) NOT NULL,
  name_en       VARCHAR(120) NOT NULL,
  brand         VARCHAR(60)  NOT NULL,
  category      ENUM('condom_49','condom_52','condom_54','condom_56','lubricant') NOT NULL,
  size_label    VARCHAR(20)  NOT NULL,
  product_type  VARCHAR(80)  NOT NULL,
  description_th TEXT,
  description_en TEXT,
  badge_th      VARCHAR(40),
  badge_en      VARCHAR(40),
  color         VARCHAR(9)   NOT NULL DEFAULT '#475d73',
  box_color     VARCHAR(9)   NOT NULL DEFAULT '#2b3a4a',
  accent_color  VARCHAR(9)   NOT NULL DEFAULT '#475d73',
  image_url     VARCHAR(500),
  price_thb     DECIMAL(7,2) NOT NULL CHECK (price_thb >= 0),
  stock_qty     INT UNSIGNED NOT NULL DEFAULT 0,
  max_stock_qty INT UNSIGNED NOT NULL DEFAULT 8,
  is_active     TINYINT(1)   NOT NULL DEFAULT 1,
  restocked_at  DATETIME     NULL,
  created_at    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT chk_stock CHECK (stock_qty <= max_stock_qty),
  INDEX idx_products_category (category),
  INDEX idx_products_brand (brand)
) ENGINE=InnoDB;

CREATE TABLE customers (
  id             BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  member_code    VARCHAR(20)  NULL UNIQUE,
  phone          VARCHAR(20)  NULL UNIQUE,
  email          VARCHAR(255) NULL UNIQUE,
  full_name      VARCHAR(120) NULL,
  birth_date     DATE         NULL,
  gender         ENUM('male','female','other','prefer_not_to_say') NULL,
  marketing_opt_in TINYINT(1) NOT NULL DEFAULT 0,
  total_purchases  INT UNSIGNED     NOT NULL DEFAULT 0,
  lifetime_value_thb DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  first_purchase_at DATETIME       NULL,
  last_purchase_at  DATETIME       NULL,
  created_at     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_customers_phone (phone),
  INDEX idx_customers_member (member_code)
) ENGINE=InnoDB;

CREATE TABLE transactions (
  id              BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  txn_code        CHAR(14)     NOT NULL UNIQUE,
  machine_id      VARCHAR(30)  NOT NULL DEFAULT 'KING-01',
  customer_id     BIGINT UNSIGNED NULL,
  product_id      INT UNSIGNED NOT NULL,
  quantity        INT UNSIGNED NOT NULL DEFAULT 1,
  unit_price_thb  DECIMAL(7,2) NOT NULL,
  total_amount_thb DECIMAL(9,2) NOT NULL,
  discount_thb    DECIMAL(7,2) NOT NULL DEFAULT 0.00,
  payment_method  ENUM('cash','promptpay_qr','credit_card') NOT NULL,
  payment_status  ENUM('pending','paid','failed','refunded','cancelled') NOT NULL DEFAULT 'pending',
  cash_inserted_thb  DECIMAL(9,2) NULL,
  change_due_thb     DECIMAL(9,2) NULL,
  dispensed       TINYINT(1)   NOT NULL DEFAULT 0,
  collected       TINYINT(1)   NOT NULL DEFAULT 0,
  slot_code       CHAR(2)      NOT NULL,
  created_at      DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  paid_at         DATETIME     NULL,
  dispensed_at    DATETIME     NULL,
  cancelled_at    DATETIME     NULL,
  CONSTRAINT fk_txn_customer FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE SET NULL,
  CONSTRAINT fk_txn_product  FOREIGN KEY (product_id)  REFERENCES products(id)  ON DELETE RESTRICT,
  CONSTRAINT chk_txn_amounts CHECK (total_amount_thb >= 0 AND discount_thb >= 0 AND quantity >= 1),
  INDEX idx_txn_created (created_at),
  INDEX idx_txn_status (payment_status),
  INDEX idx_txn_customer (customer_id),
  INDEX idx_txn_product (product_id)
) ENGINE=InnoDB;

CREATE TABLE payment_events (
  id             BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  transaction_id BIGINT UNSIGNED NOT NULL,
  event_type     ENUM('cash_inserted','qr_scan','card_tap','payment_confirmed','refund','payment_failed') NOT NULL,
  amount_thb     DECIMAL(9,2) NULL,
  reference      VARCHAR(120) NULL,
  created_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_pe_txn FOREIGN KEY (transaction_id) REFERENCES transactions(id) ON DELETE CASCADE,
  INDEX idx_pe_txn (transaction_id),
  INDEX idx_pe_created (created_at)
) ENGINE=InnoDB;

CREATE TABLE stock_movements (
  id             BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  product_id     INT UNSIGNED NOT NULL,
  movement_type  ENUM('sale','restock','manual_adjust','expired','damaged') NOT NULL,
  quantity_delta INT NOT NULL,
  stock_after    INT UNSIGNED NOT NULL,
  transaction_id BIGINT UNSIGNED NULL,
  note           VARCHAR(255) NULL,
  created_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_sm_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE,
  CONSTRAINT fk_sm_txn FOREIGN KEY (transaction_id) REFERENCES transactions(id) ON DELETE SET NULL,
  INDEX idx_sm_product (product_id),
  INDEX idx_sm_created (created_at)
) ENGINE=InnoDB;

